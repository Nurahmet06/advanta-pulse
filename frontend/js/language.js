/* =========================================================
   ТЕКУЩИЙ ЯЗЫК
   ========================================================= */

function getCurrentLanguage() {

    return localStorage.getItem("language") || "ru";

}


/* =========================================================
   ПОЛУЧИТЬ ПЕРЕВОД
   ========================================================= */

function t(key) {

    const language = getCurrentLanguage();

    return (
        translations[language]?.[key]
        ||
        translations.ru[key]
        ||
        key
    );

}


/* =========================================================
   ПРИМЕНИТЬ ЯЗЫК К СТРАНИЦЕ
   ========================================================= */

function applyLanguage() {

    const language = getCurrentLanguage();

    document.documentElement.lang = language;


    /* ОБЫЧНЫЙ ТЕКСТ */

    document
        .querySelectorAll("[data-i18n]")
        .forEach(element => {

            const key =
                element.dataset.i18n;

            element.textContent =
                t(key);

        });


    /* PLACEHOLDER У INPUT */

    document
        .querySelectorAll("[data-i18n-placeholder]")
        .forEach(element => {

            const key =
                element.dataset.i18nPlaceholder;

            element.placeholder =
                t(key);

        });


    /* ПЕРЕКЛЮЧАТЕЛЬ RU / KZ / EN */

    const selector =
        document.getElementById("languageSelect");

    if (selector) {

        selector.value =
            language;

    }

}


/* =========================================================
   СМЕНИТЬ ЯЗЫК
   ========================================================= */

function setLanguage(language) {

    if (
        language !== "ru"
        &&
        language !== "kz"
        &&
        language !== "en"
    ) {

        language = "ru";

    }


    localStorage.setItem(
        "language",
        language
    );


    applyLanguage();


    window.dispatchEvent(
        new CustomEvent(
            "languageChanged",
            {
                detail: {
                    language: language
                }
            }
        )
    );

}


/* =========================================================
   ДЕЛАЕМ ФУНКЦИИ ДОСТУПНЫМИ ДРУГИМ JS-ФАЙЛАМ
   ========================================================= */

window.translations =
    translations;

window.t =
    t;

window.setLanguage =
    setLanguage;

window.applyLanguage =
    applyLanguage;

window.getCurrentLanguage =
    getCurrentLanguage;


/* =========================================================
   ЗАПУСК
   ========================================================= */

document.addEventListener(
    "DOMContentLoaded",
    function () {

        const selector =
            document.getElementById(
                "languageSelect"
            );


        if (selector) {

            selector.value =
                getCurrentLanguage();


            selector.addEventListener(
                "change",
                function (event) {

                    setLanguage(
                        event.target.value
                    );

                }
            );

        }


        applyLanguage();

    }
);